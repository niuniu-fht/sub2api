func validateCostRule(mode string, ip, op, imgp, reqp float64) error {
	switch mode {
	case "token", "per_image", "per_request":
	default:
		return fmt.Errorf("billing_mode must be token|per_image|per_request")
	}
	for _, p := range []float64{ip, op, imgp, reqp} {
		if p < 0 {
			return fmt.Errorf("prices must be >= 0")
		}
	}
	return nil
}

// CreateCostRule 新增成本规则。
func (repo *ProfitRepository) CreateCostRule(ctx context.Context, rule ProfitCostRule) (int64, error) {
	if err := validateCostRule(rule.BillingMode, rule.InputPrice, rule.OutputPrice, rule.ImagePrice, rule.RequestPrice); err != nil {
		return 0, err
	}
	var id int64
	err := repo.queryScan(ctx, &id, `
		INSERT INTO profit_cost_rules (account_id, model, billing_mode, input_price, output_price, image_price, request_price, enabled, note)
		VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9) RETURNING id`,
		nilIfZero(rule.AccountID), rule.Model, rule.BillingMode,
		rule.InputPrice, rule.OutputPrice, rule.ImagePrice, rule.RequestPrice, rule.Enabled, rule.Note)
	return id, err
}

// UpdateCostRule 更新成本规则。
func (repo *ProfitRepository) UpdateCostRule(ctx context.Context, id int64, rule ProfitCostRule) error {
	if err := validateCostRule(rule.BillingMode, rule.InputPrice, rule.OutputPrice, rule.ImagePrice, rule.RequestPrice); err != nil {
		return err
	}
	res, err := repo.db.ExecContext(ctx, `
		UPDATE profit_cost_rules SET account_id=$2, model=$3, billing_mode=$4, input_price=$5,
		       output_price=$6, image_price=$7, request_price=$8, enabled=$9, note=$10, updated_at=now()
		WHERE id=$1`,
		id, nilIfZero(rule.AccountID), rule.Model, rule.BillingMode,
		rule.InputPrice, rule.OutputPrice, rule.ImagePrice, rule.RequestPrice, rule.Enabled, rule.Note)
	if err != nil {
		return err
	}
	if n, _ := res.RowsAffected(); n == 0 {
		return fmt.Errorf("cost rule %d not found", id)
	}
	return nil
}


// ReplaceCostRules 批量替换某账号范围（account_id 精确匹配；NULL=全局）的全部成本规则。
// 未提供有效价格的行不会被写入（未配置 = 成本 0）。
func (repo *ProfitRepository) ReplaceCostRules(ctx context.Context, accountID *int64, rules []ProfitCostRule) error {
	if len(rules) > 500 {
		return fmt.Errorf("too many rules (max 500)")
	}
	tx, err := repo.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer func() { _ = tx.Rollback() }()
	if _, err = tx.ExecContext(ctx, `DELETE FROM profit_cost_rules WHERE account_id IS NOT DISTINCT FROM $1`, nilIfZero(accountID)); err != nil {
		return err
	}
	for _, rule := range rules {
		if err := validateCostRule(rule.BillingMode, rule.InputPrice, rule.OutputPrice, rule.ImagePrice, rule.RequestPrice); err != nil {
			return err
		}
		if !rulePricePositive(rule) {
			continue // 未配置价格的模型不生成规则（成本按 0 计）
		}
		if _, err = tx.ExecContext(ctx, `
			INSERT INTO profit_cost_rules (account_id, model, billing_mode, input_price, output_price, image_price, request_price, enabled, note)
			VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)`,
			nilIfZero(accountID), strings.TrimSpace(rule.Model), rule.BillingMode,
			rule.InputPrice, rule.OutputPrice, rule.ImagePrice, rule.RequestPrice, rule.Enabled, rule.Note); err != nil {
			return err
		}
	}
	return tx.Commit()
}

func rulePricePositive(rule ProfitCostRule) bool {
	switch rule.BillingMode {
	case "per_image":
		return rule.ImagePrice > 0
	case "per_request":
		return rule.RequestPrice > 0
	default:
		return rule.InputPrice > 0 || rule.OutputPrice > 0
	}
}

