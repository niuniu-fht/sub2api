// ProfitRepository 利润统计：只读聚合 usage_logs + 收入折扣率 + 自有成本规则。
//
// 口径：
//   收入(折后) = Σ actual_cost × COALESCE(用户利润折扣率, 全局默认率)
//   上游成本   = 利润成本规则(账号×模型, 最精确优先)
//              → account_stats_cost(渠道定价快照)
//              → total_cost × account_rate_multiplier(估算兜底)
//   利润       = 收入 − 成本（可为负）
//
// 折扣率与成本规则均为利润模块私有配置，与计费倍率、渠道定价完全解耦，
// 只影响本模块的统计口径，不改动任何计费行为。
type ProfitRepository struct {
	db *sql.DB
}

// NewProfitRepository 与审计日志仓库同款：直接接收 wire 图里的 *sql.DB。
func NewProfitRepository(db *sql.DB) *ProfitRepository {
	repo := &ProfitRepository{db: db}
	// 幂等建表：独立小表，不动 users/accounts 核心表。
	_ = repo.ensureSchema(context.Background())
	return repo
}

const profitUserRatesDDL = `
CREATE TABLE IF NOT EXISTS profit_user_rates (
    user_id    bigint PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    rate       numeric(6,4) NOT NULL DEFAULT 1.0 CHECK (rate > 0 AND rate <= 10),
    note       text NOT NULL DEFAULT '',
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_profit_user_rates_user ON profit_user_rates(user_id);`

// profit_cost_rules 成本规则：account_id NULL = 任意账号；model '' = 任意模型。
// 匹配优先级：账号精确+模型精确 > 账号精确+任意模型 > 任意账号+模型精确 > 任意账号+任意模型。
const profitCostRulesDDL = `
CREATE TABLE IF NOT EXISTS profit_cost_rules (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    bigint REFERENCES accounts(id) ON DELETE CASCADE,
    model         varchar(100) NOT NULL DEFAULT '',
    billing_mode  varchar(20)  NOT NULL DEFAULT 'per_image',
    input_price   numeric(20,10) NOT NULL DEFAULT 0,
    output_price  numeric(20,10) NOT NULL DEFAULT 0,
    image_price   numeric(20,10) NOT NULL DEFAULT 0,
    request_price numeric(20,10) NOT NULL DEFAULT 0,
    enabled       boolean NOT NULL DEFAULT true,
    note          text NOT NULL DEFAULT '',
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT profit_cost_rules_mode_check CHECK (billing_mode IN ('token','per_image','per_request'))
);
CREATE INDEX IF NOT EXISTS idx_profit_cost_rules_match ON profit_cost_rules(account_id, model) WHERE enabled;`

const profitConfigSettingKey = "profit_config"

// ProfitConfig 全局利润统计配置（settings 表 JSON）。
type ProfitConfig struct {
	DefaultUserRate float64 `json:"default_user_rate"` // 未覆盖用户的收入折扣率，1.0 = 按消费原额计收入
}

func (repo *ProfitRepository) ensureSchema(ctx context.Context) error {
	if _, err := repo.db.ExecContext(ctx, profitUserRatesDDL); err != nil {
		return err
	}
	_, err := repo.db.ExecContext(ctx, profitCostRulesDDL)
	return err
}

// ─── 成本规则查询表达式（各聚合共用）───

// profitCostJoin 按行匹配成本规则（账号精确优先、模型精确优先、再按 id 稳定排序）。
const profitCostJoin = `
	LEFT JOIN LATERAL (
		SELECT r.billing_mode, r.input_price, r.output_price, r.image_price, r.request_price
		FROM profit_cost_rules r
		WHERE r.enabled
		  AND (r.account_id IS NULL OR r.account_id = u.account_id)
		  AND (r.model = '' OR r.model = u.model)
		ORDER BY (r.account_id IS NULL) ASC, (r.model = '') ASC, r.id ASC
		LIMIT 1
	) cr ON true`

// profitCostExpr 成本取值：命中利润规则按规则价；未配置规则的请求成本按 0 计。
const profitCostExpr = `CASE
	WHEN cr.billing_mode IS NOT NULL THEN CASE cr.billing_mode
		WHEN 'token' THEN (cr.input_price * COALESCE(u.input_tokens,0) + cr.output_price * COALESCE(u.output_tokens,0)) / 1000000.0
		WHEN 'per_image' THEN cr.image_price * COALESCE(u.image_count,0)
		ELSE cr.request_price
	END
	ELSE 0
END`

// profitCostConfiguredExpr 请求是否已知真实成本（规则命中或渠道快照存在）。
const profitCostConfiguredExpr = `(cr.billing_mode IS NOT NULL)`

// 聚合表达式（Postgres 的 ORDER BY 不能对别名做运算，排序时需重复完整表达式）。
const profitRevenueAgg = `COALESCE(SUM(COALESCE(u.actual_cost, 0) * COALESCE(r.rate, $1::numeric)), 0)`
const profitCostAgg = `COALESCE(SUM(` + profitCostExpr + `), 0)`

// GetConfig 读取全局配置；无记录时返回默认值。
func (repo *ProfitRepository) GetConfig(ctx context.Context) (ProfitConfig, error) {
	cfg := ProfitConfig{DefaultUserRate: 1.0}
	var raw string
	err := repo.queryScan(ctx, &raw, `SELECT value FROM settings WHERE key = $1`, profitConfigSettingKey)
	if err == sql.ErrNoRows {
		return cfg, nil
	}
	if err != nil {
		return cfg, fmt.Errorf("profit: load config: %w", err)
	}
	_ = json.Unmarshal([]byte(raw), &cfg)
	if cfg.DefaultUserRate <= 0 || cfg.DefaultUserRate > 10 {
		cfg.DefaultUserRate = 1.0
	}
	return cfg, nil
}

// SaveConfig 保存全局配置。
func (repo *ProfitRepository) SaveConfig(ctx context.Context, cfg ProfitConfig) error {
	if cfg.DefaultUserRate <= 0 || cfg.DefaultUserRate > 10 {
		return fmt.Errorf("default_user_rate must be in (0, 10]")
	}
	raw, err := json.Marshal(cfg)
	if err != nil {
		return err
	}
	_, err = repo.db.ExecContext(ctx, `
		INSERT INTO settings (key, value, updated_at) VALUES ($1, $2, now())
		ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value, updated_at = now()`,
		profitConfigSettingKey, string(raw))
	return err
}

// queryScan 单行单值查询的小工具。
func (repo *ProfitRepository) queryScan(ctx context.Context, dest any, query string, args ...any) error {
	rows, err := repo.db.QueryContext(ctx, query, args...)
	if err != nil {
		return err
	}
	defer func() { _ = rows.Close() }()
	if !rows.Next() {
		return sql.ErrNoRows
	}
	if err = rows.Scan(dest); err != nil {
		return err
	}
	return rows.Err()
}

// ─── 汇总 ───

// ProfitTotals 汇总行。
type ProfitTotals struct {
	Requests        int64   `json:"requests"`
	ImageCount      int64   `json:"image_count"`
	BilledRequests  int64   `json:"billed_requests"`         // actual_cost > 0 的请求数
	ConfiguredCost  int64   `json:"configured_cost_requests"` // 已知真实成本的请求数
	GrossRevenue    float64 `json:"gross_revenue"`           // Σ actual_cost（折前消费）
	Revenue         float64 `json:"revenue"`                 // 折后收入
	Cost            float64 `json:"cost"`                    // 上游成本
}

func (t ProfitTotals) Profit() float64 { return t.Revenue - t.Cost }
func (t ProfitTotals) Margin() float64 {
	if t.Revenue <= 0 {
		return 0
	}
	return t.Profit() / t.Revenue
}

// profitTotalsSelect 汇总列（$1 为全局默认率；需配合 profitFromJoin 使用）。
const profitTotalsSelect = `
	SELECT COUNT(*),
	       COUNT(*) FILTER (WHERE u.actual_cost > 0),
	       COUNT(*) FILTER (WHERE ` + profitCostConfiguredExpr + `),
	       COALESCE(SUM(u.image_count), 0),
	       COALESCE(SUM(u.actual_cost), 0)::float8,
	       COALESCE(SUM(COALESCE(u.actual_cost, 0) * COALESCE(r.rate, $1::numeric)), 0)::float8,
	       COALESCE(SUM(` + profitCostExpr + `), 0)::float8`

const profitFromJoin = `
	FROM usage_logs u
	LEFT JOIN profit_user_rates r ON r.user_id = u.user_id` + profitCostJoin

func (repo *ProfitRepository) scanTotals(rows *sql.Rows) (ProfitTotals, error) {
	var t ProfitTotals
	err := rows.Scan(&t.Requests, &t.BilledRequests, &t.ConfiguredCost, &t.ImageCount,
		&t.GrossRevenue, &t.Revenue, &t.Cost)
	return t, err
}

// ProfitDailyPoint 每日趋势点。
type ProfitDailyPoint struct {
	Day      string  `json:"day"`
	Requests int64   `json:"requests"`
	Revenue  float64 `json:"revenue"`
	Cost     float64 `json:"cost"`
	Profit   float64 `json:"profit"`
}

// dailySelectExpr 按日聚合的收入/成本列（$1 默认率）。
const dailySelectExpr = `
		       COALESCE(SUM(COALESCE(u.actual_cost, 0) * COALESCE(r.rate, $1::numeric)), 0)::float8,
		       COALESCE(SUM(` + profitCostExpr + `), 0)::float8`

type ProfitSummary struct {
	Totals ProfitTotals       `json:"totals"`
	Daily  []ProfitDailyPoint `json:"daily"`
}

func (repo *ProfitRepository) Summary(ctx context.Context, start, end time.Time) (ProfitSummary, error) {
	cfg, err := repo.GetConfig(ctx)
	if err != nil {
		return ProfitSummary{}, err
	}
	summary := ProfitSummary{Daily: []ProfitDailyPoint{}}

	rows, err := repo.db.QueryContext(ctx, profitTotalsSelect+profitFromJoin+
		` WHERE u.created_at >= $2 AND u.created_at < $3`, cfg.DefaultUserRate, start, end)
	if err != nil {
		return summary, fmt.Errorf("profit: summary: %w", err)
	}
	defer func() { _ = rows.Close() }()
	if rows.Next() {
		if summary.Totals, err = repo.scanTotals(rows); err != nil {
			return summary, fmt.Errorf("profit: summary scan: %w", err)
		}
	}
	if err = rows.Err(); err != nil {
		return summary, err
	}

	rows2, err := repo.db.QueryContext(ctx, `
		SELECT to_char(date_trunc('day', u.created_at), 'YYYY-MM-DD'), COUNT(*),`+dailySelectExpr+`
		`+profitFromJoin+` WHERE u.created_at >= $2 AND u.created_at < $3
		GROUP BY 1 ORDER BY 1`, cfg.DefaultUserRate, start, end)
	if err != nil {
		return summary, fmt.Errorf("profit: daily: %w", err)
	}
	defer func() { _ = rows2.Close() }()
	for rows2.Next() {
		var p ProfitDailyPoint
		if err = rows2.Scan(&p.Day, &p.Requests, &p.Revenue, &p.Cost); err != nil {
			return summary, err
		}
		p.Profit = p.Revenue - p.Cost
		summary.Daily = append(summary.Daily, p)
	}
	return summary, rows2.Err()
}

