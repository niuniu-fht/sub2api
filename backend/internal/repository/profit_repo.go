// ByAccounts 账号维度聚合（可选按用户过滤）。
func (repo *ProfitRepository) ByAccounts(ctx context.Context, start, end time.Time, userID *int64) ([]ProfitAccountRow, error) {
	cfg, err := repo.GetConfig(ctx)
	if err != nil {
		return nil, err
	}
	args := []any{cfg.DefaultUserRate, start, end}
	where := ` WHERE u.created_at >= $2 AND u.created_at < $3`
	if userID != nil && *userID > 0 {
		args = append(args, *userID)
		where += fmt.Sprintf(` AND u.user_id = $%d`, len(args))
	}
	rows, err := repo.db.QueryContext(ctx, `
		SELECT u.account_id, COALESCE(a.name, ''), COALESCE(a.platform, ''),
		       COUNT(*), COALESCE(SUM(u.image_count), 0),
		       COALESCE(SUM(COALESCE(u.actual_cost, 0) * COALESCE(r.rate, $1::numeric)), 0)::float8,
		       COALESCE(SUM(`+profitCostExpr+`), 0)::float8
		FROM usage_logs u
		LEFT JOIN profit_user_rates r ON r.user_id = u.user_id`+profitCostJoin+`
		LEFT JOIN accounts a ON a.id = u.account_id`+where+`
		GROUP BY u.account_id, a.name, a.platform
		ORDER BY COUNT(*) DESC`, args...)
	if err != nil {
		return nil, fmt.Errorf("profit: by accounts: %w", err)
	}
	defer func() { _ = rows.Close() }()
	out := []ProfitAccountRow{}
	for rows.Next() {
		var row ProfitAccountRow
		if err = rows.Scan(&row.AccountID, &row.AccountName, &row.Platform, &row.Requests, &row.Images, &row.Revenue, &row.Cost); err != nil {
			return nil, err
		}
		out = append(out, row)
	}
	return out, rows.Err()
}

// ─── 单用户详情 ───

// UserProfitDetail 单用户详情：模型维度 + 账号维度 + 每日序列。
type UserProfitDetail struct {
	Totals    ProfitTotals        `json:"totals"`
	Rate      float64             `json:"rate"`
	RateSet   bool                `json:"rate_set"`
	ByModel   []ProfitModelRow    `json:"by_model"`
	ByAccount []ProfitAccountRow  `json:"by_account"`
	Daily     []ProfitDailyPoint  `json:"daily"`
}

func (repo *ProfitRepository) UserDetail(ctx context.Context, userID int64, start, end time.Time) (*UserProfitDetail, error) {
	cfg, err := repo.GetConfig(ctx)
	if err != nil {
		return nil, err
	}
	detail := &UserProfitDetail{Rate: cfg.DefaultUserRate, ByModel: []ProfitModelRow{}, ByAccount: []ProfitAccountRow{}, Daily: []ProfitDailyPoint{}}

	if err = repo.queryScan(ctx, &detail.Rate, `SELECT rate::float8 FROM profit_user_rates WHERE user_id = $1`, userID); err == nil {
		detail.RateSet = true
	} else if err != sql.ErrNoRows {
		return nil, err
	}

	rows, err := repo.db.QueryContext(ctx, profitTotalsSelect+profitFromJoin+
		` WHERE u.created_at >= $2 AND u.created_at < $3 AND u.user_id = $4`, cfg.DefaultUserRate, start, end, userID)
	if err != nil {
		return nil, fmt.Errorf("profit: user totals: %w", err)
	}
	defer func() { _ = rows.Close() }()
	if rows.Next() {
		if detail.Totals, err = repo.scanTotals(rows); err != nil {
			return nil, err
		}
	}
	if err = rows.Err(); err != nil {
		return nil, err
	}

	modelRows, err := repo.db.QueryContext(ctx, byModelsSelect+`
		WHERE u.created_at >= $2 AND u.created_at < $3 AND u.user_id = $4
		GROUP BY u.model, a.platform
		ORDER BY ` + profitRevenueAgg + ` - ` + profitCostAgg + ` DESC`, cfg.DefaultUserRate, start, end, userID)
	if err != nil {
		return nil, fmt.Errorf("profit: user models: %w", err)
	}
	defer func() { _ = modelRows.Close() }()
	for modelRows.Next() {
		row, err := repo.scanModelRow(modelRows)
		if err != nil {
			return nil, err
		}
		detail.ByModel = append(detail.ByModel, row)
	}
	if err = modelRows.Err(); err != nil {
		return nil, err
	}

	accountRows, err := repo.ByAccounts(ctx, start, end, &userID)
	if err != nil {
		return nil, err
	}
	detail.ByAccount = accountRows

	rows2, err := repo.db.QueryContext(ctx, `
		SELECT to_char(date_trunc('day', u.created_at), 'YYYY-MM-DD'), COUNT(*),`+dailySelectExpr+`
		`+profitFromJoin+` WHERE u.created_at >= $2 AND u.created_at < $3 AND u.user_id = $4
		GROUP BY 1 ORDER BY 1`, cfg.DefaultUserRate, start, end, userID)
	if err != nil {
		return nil, fmt.Errorf("profit: user daily: %w", err)
	}
	defer func() { _ = rows2.Close() }()
	for rows2.Next() {
		var p ProfitDailyPoint
		if err = rows2.Scan(&p.Day, &p.Requests, &p.Revenue, &p.Cost); err != nil {
			return nil, err
		}
		p.Profit = p.Revenue - p.Cost
		detail.Daily = append(detail.Daily, p)
	}
	return detail, rows2.Err()
}

