// UpsertUserRate 设置/更新用户费率覆盖。
func (repo *ProfitRepository) UpsertUserRate(ctx context.Context, userID int64, rate float64, note string) error {
	if rate <= 0 || rate > 10 {
		return fmt.Errorf("rate must be in (0, 10]")
	}
	var exists bool
	if err := repo.queryScan(ctx, &exists, `SELECT EXISTS(SELECT 1 FROM users WHERE id = $1)`, userID); err != nil {
		return err
	}
	if !exists {
		return fmt.Errorf("user %d not found", userID)
	}
	_, err := repo.db.ExecContext(ctx, `
		INSERT INTO profit_user_rates (user_id, rate, note, updated_at) VALUES ($1, $2, $3, now())
		ON CONFLICT (user_id) DO UPDATE SET rate = EXCLUDED.rate, note = EXCLUDED.note, updated_at = now()`,
		userID, rate, note)
	return err
}

