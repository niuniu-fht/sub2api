// ByUsers 用户维度聚合，分页 + 可选搜索；order: profit_asc/profit_desc/revenue_desc/cost_desc。
func (repo *ProfitRepository) ByUsers(ctx context.Context, start, end time.Time, search string, order string, limit, offset int) ([]ProfitUserRow, int, error) {
	cfg, err := repo.GetConfig(ctx)
	if err != nil {
		return nil, 0, err
	}
	// where 子句独立编号（count 查询不需要费率参数——传未使用参数会让 pq 报类型推断错误）。
	where := ` WHERE u.created_at >= $1 AND u.created_at < $2`
	whereArgs := []any{start, end}
	if s := strings.TrimSpace(search); s != "" {
		whereArgs = append(whereArgs, "%"+strings.ToLower(s)+"%")
		where += fmt.Sprintf(` AND (LOWER(us.email) LIKE $%d OR LOWER(us.username) LIKE $%d)`, len(whereArgs), len(whereArgs))
	}
	profitOrderExpr := profitRevenueAgg + " - " + profitCostAgg
	orderExpr := map[string]string{
		"profit_asc":   profitOrderExpr + " ASC",
		"profit_desc":  profitOrderExpr + " DESC",
		"revenue_desc": profitRevenueAgg + " DESC",
		"cost_desc":    profitCostAgg + " DESC",
	}[order]
	if orderExpr == "" {
		orderExpr = profitOrderExpr + " DESC"
	}

	var total int
	if err = repo.queryScan(ctx, &total, `
		SELECT COUNT(*) FROM (
			SELECT u.user_id FROM usage_logs u
			LEFT JOIN profit_user_rates r ON r.user_id = u.user_id`+profitCostJoin+`
			JOIN users us ON us.id = u.user_id`+where+`
			GROUP BY u.user_id) t`, whereArgs...); err != nil {
		return nil, 0, fmt.Errorf("profit: by users count: %w", err)
	}

	// 主查询费率占 $1，where 参数整体后移一位。
	whereShifted := shiftPlaceholders(where, 1)
	args := append([]any{cfg.DefaultUserRate}, whereArgs...)
	args = append(args, limit, offset)
	rows, err := repo.db.QueryContext(ctx, `
		SELECT u.user_id, us.email, COALESCE(us.username, ''),
		       COALESCE(r.rate, $1::numeric)::float8, r.rate IS NOT NULL,
		       COUNT(*), COALESCE(SUM(u.image_count), 0),
		       COALESCE(SUM(COALESCE(u.actual_cost, 0) * COALESCE(r.rate, $1::numeric)), 0)::float8 AS revenue,
		       COALESCE(SUM(`+profitCostExpr+`), 0)::float8 AS cost
		FROM usage_logs u
		LEFT JOIN profit_user_rates r ON r.user_id = u.user_id`+profitCostJoin+`
		JOIN users us ON us.id = u.user_id`+whereShifted+`
		GROUP BY u.user_id, us.email, us.username, r.rate
		ORDER BY `+orderExpr+`, u.user_id
		LIMIT $`+fmt.Sprint(len(args)-1)+` OFFSET $`+fmt.Sprint(len(args)), args...)
	if err != nil {
		return nil, 0, fmt.Errorf("profit: by users: %w", err)
	}
	defer func() { _ = rows.Close() }()
	out := []ProfitUserRow{}
	for rows.Next() {
		var row ProfitUserRow
		if err = rows.Scan(&row.UserID, &row.Email, &row.Name, &row.Rate, &row.RateSet, &row.Requests, &row.Images, &row.Revenue, &row.Cost); err != nil {
			return nil, 0, err
		}
		out = append(out, row)
	}
	return out, total, rows.Err()
}

// ─── 模型维度 ───

// ProfitModelRow 模型维度行。
type ProfitModelRow struct {
	Model    string  `json:"model"`
	Platform string  `json:"platform"`
	Requests int64   `json:"requests"`
	Images   int64   `json:"images"`
	GrossRev float64 `json:"gross_revenue"`
	Revenue  float64 `json:"revenue"`
	Cost     float64 `json:"cost"`
}

func (r ProfitModelRow) Profit() float64 { return r.Revenue - r.Cost }

// byModelsSelect 模型维度列（$1 默认率），可选 user_id 过滤（$n 由调用方拼）。
const byModelsSelect = `
		SELECT u.model, COALESCE(a.platform, ''),
		       COUNT(*), COALESCE(SUM(u.image_count), 0),
		       COALESCE(SUM(u.actual_cost), 0)::float8,
		       COALESCE(SUM(COALESCE(u.actual_cost, 0) * COALESCE(r.rate, $1::numeric)), 0)::float8,
		       COALESCE(SUM(` + profitCostExpr + `), 0)::float8
		FROM usage_logs u
		LEFT JOIN profit_user_rates r ON r.user_id = u.user_id` + profitCostJoin + `
		LEFT JOIN accounts a ON a.id = u.account_id`

func (repo *ProfitRepository) scanModelRow(rows *sql.Rows) (ProfitModelRow, error) {
	var row ProfitModelRow
	err := rows.Scan(&row.Model, &row.Platform, &row.Requests, &row.Images, &row.GrossRev, &row.Revenue, &row.Cost)
	return row, err
}

// ByModels 全局模型维度聚合，按利润降序。
func (repo *ProfitRepository) ByModels(ctx context.Context, start, end time.Time) ([]ProfitModelRow, error) {
	cfg, err := repo.GetConfig(ctx)
	if err != nil {
		return nil, err
	}
	rows, err := repo.db.QueryContext(ctx, byModelsSelect+`
		WHERE u.created_at >= $2 AND u.created_at < $3
		GROUP BY u.model, a.platform
		ORDER BY ` + profitRevenueAgg + ` - ` + profitCostAgg + ` DESC`, cfg.DefaultUserRate, start, end)
	if err != nil {
		return nil, fmt.Errorf("profit: by models: %w", err)
	}
	defer func() { _ = rows.Close() }()
	out := []ProfitModelRow{}
	for rows.Next() {
		row, err := repo.scanModelRow(rows)
		if err != nil {
			return nil, err
		}
		out = append(out, row)
	}
	return out, rows.Err()
}

